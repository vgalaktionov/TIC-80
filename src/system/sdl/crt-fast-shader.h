// Linear-light Gaussian filtering, with adjacent taps combined by the sampler.
static const char FastPixelShader[] =
    "#version 110\n"
    "varying vec2 texCoord;\n"
    "uniform sampler2D source;\n"
    "uniform sampler2D weights;\n"
    "vec3 filterCRT(vec2 pos) {\n"
    " vec2 p = pos * vec2(256.0,144.0) - 0.5;\n"
    " vec2 base = floor(p), f = p - base;\n"
    " vec3 h = texture2D(weights,vec2((f.x*1023.0+0.5)/1024.0,0.25)).rgb;\n"
    " vec2 v = texture2D(weights,vec2((f.y*1023.0+0.5)/1024.0,0.75)).rg;\n"
    " vec2 x = (base.x + h.xy + 0.5)/256.0;\n"
    " float y = (base.y + v.x + 0.5)/144.0;\n"
    " return mix(texture2D(source,vec2(x.y,y)).rgb,\n"
    "            texture2D(source,vec2(x.x,y)).rgb,h.z)*v.y;\n"
    "}\n"
    "void main() {\n"
    " vec2 p = texCoord*2.0-1.0;\n"
    " p *= vec2(1.0+p.y*p.y/64.0,1.0+p.x*p.x/48.0);\n"
    " vec2 uv = p*0.5+0.5;\n"
    " vec2 edge = min(uv,1.0-uv);\n"
    " vec2 aa = max(fwidth(uv),vec2(0.000001));\n"
    " vec2 coverage = smoothstep(-0.5*aa,0.5*aa,edge);\n"
    " float phase = fract((gl_FragCoord.x+gl_FragCoord.y*3.0)/6.0);\n"
    " vec3 mask = vec3(0.5)+step(vec3(0.0,0.333,0.666),vec3(phase))\n"
    "                      -step(vec3(0.333,0.666,1.0),vec3(phase));\n"
    " vec3 c = filterCRT(uv)*mask;\n"
    " c = mix(c*12.92,1.055*pow(max(c,vec3(0.0031308)),vec3(0.41666))-0.055,\n"
    "         step(vec3(0.0031308),c));\n"
    " gl_FragColor = vec4(c*coverage.x*coverage.y,1.0);\n"
    "}\n";
